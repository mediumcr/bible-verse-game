const NORMALIZE = {
  '‘': "'", '’': "'", '“': '"', '”': '"', '–': '-', '…': '...',
  ' ': ' ', '•': '·', '‑': '-', '−': '-', 'ç': 'c', 'Ç': 'C',
};

const glyphs = new Map();

function parse(def, top) {
  const rows = def.split('|');
  let min = 99, max = -1;
  for (const r of rows) for (let i = 0; i < r.length; i++) if (r[i] === '#') { if (i < min) min = i; if (i > max) max = i; }
  if (max < 0) { min = 0; max = 2; }
  return { rows, top, min, w: max - min + 1 };
}

for (const [ch, def] of Object.entries(G)) glyphs.set(ch, parse(def, OFFSET[ch] || 0));
for (const [ch, [base, acc]] of Object.entries(ACCENTED)) {
  const b = G[base].split('|');
  if (base === base.toLowerCase()) {
    const rows = [ACC_LO[acc][0], ACC_LO[acc][1], '.....', ...b.slice(2)];
    glyphs.set(ch, parse(rows.join('|'), -1));
  } else {
    const rows = [ACC_UP[acc], '.....', ...b];
    glyphs.set(ch, parse(rows.join('|'), -2));
  }
}
const SPACE_W = 3;

export function normalizeText(s) {
  let out = '';
  for (const ch of String(s)) out += NORMALIZE[ch] !== undefined ? NORMALIZE[ch] : ch;
  return out;
}

function glyphFor(ch) {
  return glyphs.get(ch) || glyphs.get('?');
}

export function hasGlyph(ch) {
  return ch === ' ' || ch === '\n' || glyphs.has(ch) || NORMALIZE[ch] !== undefined;
}

const cache = new Map();
function glyphCanvas(ch, color) {
  const key = ch + '\u0000' + color;
  let c = cache.get(key);
  if (c) return c;
  const g = glyphFor(ch);
  c = document.createElement('canvas');
  c.width = g.w; c.height = LINE_H;
  const x = c.getContext('2d');
  x.fillStyle = color;
  g.rows.forEach((row, ri) => {
    const y = BASE_Y + g.top + ri;
    for (let i = 0; i < row.length; i++) if (row[i] === '#') x.fillRect(i - g.min, y, 1, 1);
  });
  cache.set(key, c);
  return c;
}

export function charWidth(ch) {
  if (ch === ' ') return SPACE_W;
  return glyphFor(ch).w;
}

export function measure(text, scale = 1) {
  const s = normalizeText(text);
  let w = 0, first = true;
  for (const ch of s) {
    if (!first) w += 1;
    w += charWidth(ch);
    first = false;
  }
  return w * scale;
}

// Draw single-line text. y is the top of the 11px line box.
export function drawText(ctx, text, x, y, color = '#f8f8f8', opts = {}) {
  const scale = opts.scale || 1;
  const s = normalizeText(text);
  if (opts.align === 'center') x -= Math.floor(measure(s, scale) / 2);
  else if (opts.align === 'right') x -= measure(s, scale);
  x = Math.round(x); y = Math.round(y);
  if (opts.shadow) drawRun(ctx, s, x + scale, y + scale, opts.shadow, scale, opts.max);
  return drawRun(ctx, s, x, y, color, scale, opts.max);
}

function drawRun(ctx, s, x, y, color, scale, max) {
  let cx = x, n = 0;
  for (const ch of s) {
    if (max !== undefined && n >= max) break;
    n++;
    if (ch === ' ') { cx += (SPACE_W + 1) * scale; continue; }
    const c = glyphCanvas(ch, color);
    if (scale === 1) ctx.drawImage(c, cx, y);
    else ctx.drawImage(c, 0, 0, c.width, c.height, cx, y, c.width * scale, c.height * scale);
    cx += (c.width + 1) * scale;
  }
  return cx - x;
}

// Word-wrap into lines no wider than maxW. Honors '\n'.
export function wrapText(text, maxW, scale = 1) {
  const out = [];
  const paras = normalizeText(text).split('\n');
  for (const para of paras) {
    const words = para.split(' ').filter((w, i, a) => w.length || a.length === 1);
    let line = '';
    for (let word of words) {
      const cand = line ? line + ' ' + word : word;
      if (measure(cand, scale) <= maxW) { line = cand; continue; }
      if (line) out.push(line);
      // break overly long words
      while (measure(word, scale) > maxW) {
        let i = word.length - 1;
        while (i > 1 && measure(word.slice(0, i), scale) > maxW) i--;
        out.push(word.slice(0, i));
        word = word.slice(i);
      }
      line = word;
    }
    out.push(line);
  }
  return out;
}
